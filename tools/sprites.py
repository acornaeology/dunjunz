"""Write the game's sprite sheet: one PNG per sprite and a Markdown page.

    uv run python tools/sprites.py

Reads the sprite tables (sprite_addr_lo/hi at &1AE0/&1B58, widths at
&1BD0, heights at &1C48) and the sprite data from the official disc's
resident image as the game starts (tools/runtime_images.py), with the
wall sprite (&2D00) taken from level 1, as at the first frame of play.
Each sprite is drawn in the default MODE 2 palette, which the game never
changes, each pixel twice as wide as it is tall, as on the screen.
Flashing colours (8-15) are drawn in their first colour and marked.

Writes docs/sprites/sprite_NN.png and docs/sprites.md.
"""

import io
import sys
import zipfile
from pathlib import Path

from PIL import Image

REPO_DIRPATH = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_DIRPATH / "tools"))
sys.path.insert(0, str(REPO_DIRPATH))
from runtime_images import disc_image  # noqa: E402
from dunjunz_common.game import SPRITES  # noqa: E402

DOCS_DIRPATH = REPO_DIRPATH / "docs"
IMAGES_DIRNAME = "sprites"
PAGE_FILEPATH = DOCS_DIRPATH / "sprites.md"
DISC_ZIP_FILEPATH = REPO_DIRPATH / "versions" / "dunjunz-disc" / "Dunjunz.zip"

SPRITE_COUNT = 120
ADDR_LO, ADDR_HI, WIDTHS, HEIGHTS = 0x1AE0, 0x1B58, 0x1BD0, 0x1C48
WALL_SPRITE, WALL_IN_LEVEL, WALL_SIZE = 0x2D00, 0x280, 0x30
LEVEL_BASE = 0x6B00
PIXEL_WIDTH, PIXEL_HEIGHT = 8, 4

PALETTE = [(0, 0, 0), (255, 0, 0), (0, 255, 0), (255, 255, 0),
           (0, 0, 255), (255, 0, 255), (0, 255, 255), (255, 255, 255)]
COLOUR_NAMES = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]


def level_1() -> bytes:
    """The official disc's level 1, decrypted (each byte is XORed with the
    low byte of its address at &6B00)."""
    with zipfile.ZipFile(DISC_ZIP_FILEPATH) as z:
        name = next(n for n in z.namelist() if n.split("/")[-1].lower() == "level1")
        data = z.read(name)
    return bytes(b ^ ((LEVEL_BASE + i) & 0xFF) for i, b in enumerate(data))


def mode2_pixels(byte):
    """The logical colours of a MODE 2 byte's left and right pixels."""
    def colour(bits):
        return sum(((byte >> bit) & 1) << place for place, bit in enumerate(bits))
    return colour((1, 3, 5, 7)), colour((0, 2, 4, 6))


def sprite_rows(image, addr, width, height):
    return [[c for col in range(width) for c in mode2_pixels(image[addr + row * width + col])]
            for row in range(height)]


def sprite_png(rows) -> Image.Image:
    picture = Image.new("RGB", (len(rows[0]) * PIXEL_WIDTH, len(rows) * PIXEL_HEIGHT))
    for y, row in enumerate(rows):
        for x, colour in enumerate(row):
            picture.paste(PALETTE[colour & 7], (x * PIXEL_WIDTH, y * PIXEL_HEIGHT,
                                                (x + 1) * PIXEL_WIDTH, (y + 1) * PIXEL_HEIGHT))
    return picture


def label_of(number, name, addr):
    """The listing's label for a sprite's data (game.annotate_sprites)."""
    if addr == WALL_SPRITE:
        return "wall_sprite"
    if name.startswith("drainer"):
        return "sprite_drainer"
    if addr == 0x04CF:
        return "sprite_blank"
    return "sprite_" + name


INTRODUCTION = """\
# The sprites

<!-- Generated by tools/sprites.py: edit that, not this page. -->

The game draws everything but the walls of the views and the status
panel through `plot_sprite`, by sprite number: 120 sprites, named in the
listings by number (`spr_` constants where the code names one). Each sprite's data address, width in
bytes and height in rows are in four tables of 120 bytes,
[`sprite_addr_lo`](address:1AE0@disc?hex),
[`sprite_addr_hi`](address:1B58@disc?hex),
[`sprite_widths`](address:1BD0@disc?hex) and
[`sprite_heights`](address:1C48@disc?hex). The data is stored row by
row, each byte two MODE 2 pixels (the left pixel's colour in bits 7, 5,
3 and 1, the right's in bits 6, 4, 2 and 0), and is stored over the
screen rather than masked, so black is drawn as black.

This is the official disc's Model B set as the game starts; the tables
and the sprite data are the same in Ole's crack and the sideways RAM
hack. The tables change while the game runs: a hero going down the exit
shrinks their own sprites, and the victory sequence changes some entries
and data. The wall sprite,
&00, is replaced by each level's own (bytes &280-&2AF of the level file;
see [level-format.md](level-format.md)); the one shown is level 1's.
Several numbers share data: the twelve drainer sprites are one picture,
and &15, &1A and &77 are the blank sprite.

The pictures use the default MODE 2 palette, which the game never
changes, with each pixel twice as wide as it is tall, as on the screen.
A sprite marked *flashing* uses one of colours 8-15, which alternate
between two colours; it is drawn in the first.

| No. | Sprite | Name | Size (pixels) | Data |
|---|---|---|---|---|
"""


def main():
    image = disc_image()
    wall = level_1()[WALL_IN_LEVEL:WALL_IN_LEVEL + WALL_SIZE]
    for i, b in enumerate(wall):
        image[WALL_SPRITE + i] = b
    images_dirpath = DOCS_DIRPATH / IMAGES_DIRNAME
    images_dirpath.mkdir(exist_ok=True)
    lines = [INTRODUCTION]
    for number, name, addr, width, height in SPRITES:
        table_addr = image[ADDR_LO + number] | image[ADDR_HI + number] << 8
        table_size = image[WIDTHS + number], image[HEIGHTS + number]
        if (table_addr, table_size) != (addr, (width, height)):
            raise SystemExit(f"sprite &{number:02X}: tables give &{table_addr:04X} "
                             f"{table_size}, game.SPRITES {addr:04X} {(width, height)}")
        rows = sprite_rows(image, addr, width, height)
        flashing = sorted({c for row in rows for c in row if c >= 8})
        png_filename = f"sprite_{number:02X}.png"
        buffer = io.BytesIO()
        sprite_png(rows).save(buffer, format="PNG", optimize=True)
        (images_dirpath / png_filename).write_bytes(buffer.getvalue())
        note = ""
        if flashing:
            note = "; *flashing* " + ", ".join(
                f"{c} ({COLOUR_NAMES[c - 8]}/{COLOUR_NAMES[15 - c]})" for c in flashing)
        label = label_of(number, name, addr)
        lines.append(
            f"| &{number:02X} | ![sprite &{number:02X}]({IMAGES_DIRNAME}/{png_filename}) "
            f"| `{name}` | {width * 2}×{height}{note} "
            f"| [`{label}`](address:{addr:04X}@disc?hex) |\n")
    PAGE_FILEPATH.write_text("".join(lines))
    print(f"Wrote {PAGE_FILEPATH} and {SPRITE_COUNT} images in {images_dirpath}")


if __name__ == "__main__":
    main()
